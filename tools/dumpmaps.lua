-- Dump the live keymaps of a LazyVim session to site/keymaps.js.
-- Run via: ./practice --keys   (opens nvim headless in the practice project)
local out_path = vim.env.DOJO_OUT or "keymaps.js"
local out, seen = {}, {}

local function norm(lhs)
  lhs = lhs:gsub("^ ", "<leader>"):gsub(" ", "<Space>")
  return lhs
end

local function grab(list, ctx)
  for _, m in ipairs(list) do
    local lhs = m.lhs
    if lhs and not lhs:match("^<Plug>") and not lhs:match("^<SNR>") and m.desc and m.desc ~= ""
      and not m.desc:match("^:") -- nvim built-in defaults
      and m.desc ~= "which_key_ignore"
      and m.mode ~= "v" -- same maps as x
    then
      local item = { ctx = ctx, mode = m.mode, lhs = norm(lhs), desc = m.desc }
      local k = ctx .. "\0" .. item.mode .. "\0" .. item.lhs
      if not seen[k] then
        seen[k] = true
        table.insert(out, item)
      end
    end
  end
end

local done = false
local function finish()
  if done then return end
  done = true
  local f = assert(io.open(out_path, "w"))
  f:write("// Generated by tools/dumpmaps.lua from a live LazyVim session.\nwindow.KEYMAPS = ")
  f:write(vim.json.encode(out))
  f:write(";\n")
  f:close()
  vim.cmd("qa!")
end

vim.defer_fn(function()
  vim.cmd("doautocmd UIEnter") -- LazyVim registers most keys on VeryLazy
  vim.cmd("edit main.lua")
  local n = 0
  local function wait()
    n = n + 1
    if (#vim.lsp.get_clients({ bufnr = 0 }) > 0 and n > 16) or n > 60 then
      for _, mode in ipairs({ "n", "i", "t", "x" }) do
        grab(vim.api.nvim_get_keymap(mode), "global")
        grab(vim.api.nvim_buf_get_keymap(0, mode), "lua-buffer")
      end
      pcall(vim.cmd, "Neotree show")
      vim.defer_fn(function()
        for _, w in ipairs(vim.api.nvim_list_wins()) do
          local b = vim.api.nvim_win_get_buf(w)
          if vim.bo[b].filetype == "neo-tree" then grab(vim.api.nvim_buf_get_keymap(b, "n"), "neotree") end
        end
        finish()
      end, 1500)
      return
    end
    vim.defer_fn(wait, 250)
  end
  wait()
end, 800)
vim.defer_fn(finish, 40000)
